function reviews(seed: Array<[string, number, string]>, now: number): Review[] {
  return seed.map(([author, rating, text], i) => ({
    id: `rv_${author}_${i}`,
    author,
    rating,
    text,
    createdAt: now - (i + 1) * 3.3 * DAY,
  }));
}

